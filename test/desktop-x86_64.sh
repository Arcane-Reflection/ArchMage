#!/usr/bin/env bash
# desktop-x86_64.sh — build the ArchMage DESKTOP x86_64 image.
#
# Two modes (D-0 handoff, docs/internal/HANDOFF-OMARCHY-BASE.md):
#
#   default   Omarchy 4.5.x base: the desktop experience (Hyprland + quickshell
#             shell, SDDM + autologin, limine + snapper rollback, omarchy-*
#             tooling, CN-ready i18n) comes from the upstream [omarchy] stable
#             repo, version-pinned via test/omarchy-version.txt. We overlay the
#             CN layer (archmage-desktop) + the brand layer (archmage-branding,
#             L1+L2 rebrand per docs/internal/omarchy-rebrand-inventory.md).
#             ESP sits at /boot (limine-entry-tool convention); entries are
#             generated by limine-mkinitcpio; OVMF boots the limine fallback
#             path \EFI\BOOT\BOOTX64.EFI.
#
#   --legacy  the pre-D-0 builder: bare Arch + hand-rolled Hyprland stack,
#             GRUB + greetd. Kept verbatim for comparison/rollback of the
#             builder itself; the Omarchy base replaces it once D-0.3 boots.
#
# Both modes: staging-repo-x86_64 acquisition (SigLevel Required + lsign
# discipline), btrfs subvolume layout (@ @var @snapshots) with snapper
# preconfigured, structural gates where the exit code IS the gate.
#
# Runs as ROOT inside a privileged archlinux:base container (loop devices +
# mounts). Self-wraps via docker when pacman is missing, same pattern as
# test/mkrootfs-x86_64.sh.
#
# Usage:
#   bash test/desktop-x86_64.sh [--legacy] [--from-ci | --repo-dir PATH] [--out IMG]
#
#   --legacy       build the pre-D-0 bare-Arch image instead of the Omarchy base
#   --from-ci      download the staging-repo-x86_64 artifact of the latest
#                  successful packages.yml run on main (GH_TOKEN required;
#                  desktop staging repo, 01-01 contract sibling).
#   --repo-dir DIR use an already-acquired staging-repo-x86_64 directory.
#   --out IMG      output image path (default test/build/desktop/rootfs.img).
#
# Disk layout (rollback-ready, mirrors the phone image discipline):
#   GPT: p1 ESP (vfat, AMDESP) | p2 btrfs -L archmage-desktop
#   btrfs subvolumes: @ (root), @var (NoCOW), @snapshots — snapper/snap-pac
#   preconfigured so the desktop gets the same rollback story as the phone.
#   ESP size: 512M legacy, 1G Omarchy (limine copies kernels+initramfs into
#   the ESP at $ESP_PATH/$machine_id/<kernel>/).
#
# Gates (structural, exit code IS the gate):
#   omarchy mode: Hyprland/quickshell/SDDM stack binaries, linux-omarchy +
#   pinned omarchy meta in the pacman db, ArchMage os-release, archmage*
#   entry symlinks, SDDM archmage theme + autologin, limine boot files +
#   enrolled entries, CN locale + fonts + fcitx5, user archmage, btrfs/
#   snapper layout.
#   legacy mode: Hyprland stack binaries, CN locale + fonts, fcitx5, gum/fzf,
#   archmage-desktop in the pacman db, GRUB installed, subvolumes + snapper
#   config, user archmage present.

set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
OUT_DIR="$REPO_ROOT/test/build/desktop"
OUT_IMG="$OUT_DIR/rootfs.img"
REPO_DIR=""
FROM_CI=no
LEGACY=no
run_id=""

die() { printf '::error::FATAL: %s\n' "$*" >&2; exit 1; }
info() { printf '==> %s\n' "$*"; }

# Anonymous-debug channel: CI step logs are not readable without admin, and
# the check-run annotation for a bare exit is useless. Tee the whole console
# to a log; on a non-zero exit the EXIT trap re-emits the tail as ::error::
# workflow annotations (newline-encoded %0A). EXIT (not ERR) so explicit
# `exit 1` gate paths are covered too.
mkdir -p "$OUT_DIR"
exec > >(tee "$OUT_DIR/build-console.log") 2>&1
on_err() {
    rc=$?
    [ "$rc" -eq 0 ] && return 0
    joined="$(tail -n 25 "$OUT_DIR/build-console.log" | cut -c1-150 \
        | awk '{printf "%s%%0A", $0}')"
    printf '::error::desktop build failed rc=%s\n' "$rc" >&2
    printf '::error::console tail: %s\n' "${joined:-<nothing captured>}" >&2
}
trap on_err EXIT

while [ $# -gt 0 ]; do
    case "$1" in
        --legacy) LEGACY=yes ;;
        --from-ci) FROM_CI=yes ;;
        --repo-dir) [ $# -ge 2 ] || die "--repo-dir needs a PATH"; REPO_DIR=$2; shift ;;
        --out) [ $# -ge 2 ] || die "--out needs a PATH"; OUT_IMG=$2; shift ;;
        -h|--help) sed -n '2,42p' "$0" | grep -E '^#'; exit 0 ;;
        *) die "unknown argument: $1" ;;
    esac
    shift
done

# ---- self-wrap: privileged archlinux:base container when pacman missing ----
if ! command -v pacman >/dev/null 2>&1; then
    command -v docker >/dev/null 2>&1 || die "no pacman and no docker — cannot build"
    info "self-wrapping into a privileged archlinux:base container"
    # Pull EXPLICITLY with retries + annotations: an exec'd `docker run`
    # that dies on a failed/hung pull (Docker Hub rate-limits GH runner IP
    # pools) exits the replaced shell with no trap — six silent 3-minute
    # failures. A visible, retried pull turns that into a diagnosable event.
    pull_ok=no
    for attempt in 1 2 3 4 5; do
        if docker pull --platform linux/x86_64 archlinux:base-devel; then
            pull_ok=yes
            break
        fi
        printf '::warning::docker pull attempt %s failed\n' "$attempt" >&2
        sleep 20
    done
    [ "$pull_ok" = yes ] || die "docker pull failed after 5 attempts (Docker Hub unreachable/rate-limited)"
    mkdir -p "$REPO_ROOT/test/build/desktop/pacman-cache"
    # Pass the PARSED state, not "$@": the arg-parse loop shifts options
    # away, so after parsing "$@" is empty and the inner script would run
    # with FROM_CI=no (observed live: inner resolve skipped, staging check
    # died on an unset run_id). --legacy must ride the same way.
    inner_args=()
    [ "$LEGACY" = yes ] && inner_args+=(--legacy)
    [ "$FROM_CI" = yes ] && inner_args+=(--from-ci)
    [ -n "$REPO_DIR" ] && inner_args+=(--repo-dir "$REPO_DIR")
    exec docker run --rm --privileged --platform linux/x86_64 \
        -v "$REPO_ROOT":/w -w /w \
        -v "$REPO_ROOT/test/build/desktop/pacman-cache":/var/cache/pacman/pkg \
        -e GH_TOKEN="${GH_TOKEN:-}" -e ARCHMAGE_IN_CONTAINER=1 \
        -e ARCHMAGE_DESKTOP_MIRROR_ORDER="${ARCHMAGE_DESKTOP_MIRROR_ORDER:-}" \
        archlinux:base-devel \
        bash test/desktop-x86_64.sh "${inner_args[@]}"
fi

[ "$(id -u)" = 0 ] || die "must run as root (inside the privileged container)"

# GH Actions docker blocks Landlock; pacman 7 sandbox cannot be satisfied in
# job containers — container-own pacman only (01-02 decision, throwaway root).
# EXACT match: newer archlinux images ship DisableSandboxFilesystem, and the
# old prefix grep ('^DisableSandbox') treated that as done and never added
# plain DisableSandbox — runc VMs that cannot install a seccomp filter
# (colima + Rosetta) then died at "restricting syscalls via seccomp: 22".
grep -q '^DisableSandbox$' /etc/pacman.conf || sed -i 's/^\[options\]$/[options]\nDisableSandbox/' /etc/pacman.conf
# archlinux:base ships a pacman.conf WITHOUT [extra] — gh and the desktop
# stack live in extra. Enable it (idempotent) before any pacman -Sy.
grep -q '^\[extra\]' /etc/pacman.conf || printf '\n[extra]\nInclude = /etc/pacman.d/mirrorlist\n' >> /etc/pacman.conf
# Deterministic dual mirrorlist BEFORE any pacman -Sy. Order is
# environment-aware: CI runners (US-hosted) want the geo CDN first; local
# CN-network builds want TUNA first (the geo CDN can HANG — not just slow —
# from CN networks; measured live 2026-11-10). Set
# ARCHMAGE_DESKTOP_MIRROR_ORDER=cn for local builds.
if [ "${ARCHMAGE_DESKTOP_MIRROR_ORDER:-geo}" = "cn" ]; then
    printf '%s\n' \
        'Server = https://mirrors.tuna.tsinghua.edu.cn/archlinux/$repo/os/$arch' \
        'Server = https://geo.mirror.pkgbuild.com/$repo/os/$arch' \
        > /etc/pacman.d/mirrorlist
else
    printf '%s\n' \
        'Server = https://geo.mirror.pkgbuild.com/$repo/os/$arch' \
        'Server = https://mirrors.tuna.tsinghua.edu.cn/archlinux/$repo/os/$arch' \
        > /etc/pacman.d/mirrorlist
fi
# Full -Syu: rolling-distro partial-upgrade trap — '-Sy pkg' pulled a
# new openssl mid-transition and broke the container's own pacman
# (libssl.so.3 gone, run 42799345601). Upgrade EVERYTHING in one
# transaction so the throwaway container is ABI-consistent.
pacman -Syu --noconfirm --needed arch-install-scripts btrfs-progs dosfstools \
    e2fsprogs gnupg jq sudo github-cli

# ---- mode constants ---------------------------------------------------------
if [ "$LEGACY" = yes ]; then
    ESP_MB=512
else
    ESP_MB=1024   # limine copies kernels + initramfs into the ESP
fi
esp_sectors=$((ESP_MB * 1024 * 1024 / 512))
root_start=$((2048 + esp_sectors))

# ---- staging repo acquisition (both modes) ---------------------------------
STAGING="$OUT_DIR/staging"
mkdir -p "$STAGING"
if [ "$FROM_CI" = yes ]; then
    [ -n "${GH_TOKEN:-}" ] || die "--from-ci needs GH_TOKEN"
    run_id="$(gh run list --repo "${ARCHMAGE_GH_REPO:-Arcane-Reflection/ArchMage}" \
        --workflow packages.yml --branch main --status success --limit 1 \
        --json databaseId --jq '.[0].databaseId')"
    [ -n "$run_id" ] || die "no successful packages.yml run on main yet"
    info "downloading staging-repo-x86_64 from packages run $run_id"
    rm -rf "$STAGING"; mkdir -p "$STAGING"
    gh run download "$run_id" --repo "${ARCHMAGE_GH_REPO:-Arcane-Reflection/ArchMage}" \
        --name staging-repo-x86_64 --dir "$STAGING"
elif [ -n "$REPO_DIR" ]; then
    rm -rf "$STAGING"; cp -a "$REPO_DIR/." "$STAGING/"
fi
echo "DEBUG: FROM_CI=$FROM_CI REPO_DIR=$REPO_DIR run_id=${run_id:-UNSET} STAGING=$STAGING"
if [ ! -f "$STAGING/cn.db.tar.zst" ]; then
    echo "::error::staging repo lacks cn.db.tar.zst (run_id=${run_id:-UNSET}) — downloaded content:"
    ls -la "$STAGING" >&2 || true
    die "wrong artifact downloaded?"
fi
[ -f "$STAGING/staging-key.asc" ] || die "staging repo lacks staging-key.asc"
# packages.yml keeps producing cn.db.tar.zst; the [archmage-testing] section
# requests archmage-testing.db — provide both names (mkrootfs 03-03 pattern).
ln -sfn cn.db.tar.zst "$STAGING/archmage-testing.db"
[ -s "$STAGING/cn.db.tar.zst.sig" ] && \
    ln -sfn cn.db.tar.zst.sig "$STAGING/archmage-testing.db.sig" || true

# ---- keyrings: archlinux + staging (both modes) + omarchy (D-0 mode) -------
gpgdir="$OUT_DIR/pacman-keyring"
mkdir -p "$gpgdir"; chmod 700 "$gpgdir"
export GNUPGHOME="$gpgdir"
pacman-key --init >/dev/null 2>&1
# The pacstrap GPGDir keyring needs ARCHLINUX keys (repo packages) AND the
# staging key (overlay packages); the host DEFAULT keyring needs the staging
# key too, because pacstrap -K seeds the image's keyring from it (first-boot
# archmage-testing sig verification would otherwise fail).
pacman-key --populate archlinux >/dev/null 2>&1
pacman-key --add "$STAGING/staging-key.asc" >/dev/null 2>&1
fpr="$(awk '/^FINGERPRINT:/ {print $2}' "$STAGING/FINGERPRINT.txt")"
[ -n "$fpr" ] || die "cannot parse FINGERPRINT.txt"
pacman-key --lsign-key "$fpr" >/dev/null 2>&1
# Mirror into the pacstrap GPGDir keyring.
pacman-key --gpgdir "$gpgdir" --init >/dev/null 2>&1
pacman-key --gpgdir "$gpgdir" --populate archlinux >/dev/null 2>&1
pacman-key --gpgdir "$gpgdir" --add "$STAGING/staging-key.asc" >/dev/null 2>&1
pacman-key --gpgdir "$gpgdir" --lsign-key "$fpr" >/dev/null 2>&1
info "staging key $fpr imported and locally signed (default + pacstrap keyrings)"

OMARCHY_VERSION=""
if [ "$LEGACY" = no ]; then
    # ---- D-0.1: pin + omarchy keyring bootstrap -----------------------------
    OMARCHY_VERSION="$(tr -d '[:space:]' < "$REPO_ROOT/test/omarchy-version.txt")"
    printf '%s' "$OMARCHY_VERSION" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+-[0-9]+$' \
        || die "test/omarchy-version.txt: not a pkgver-pkgrel ($OMARCHY_VERSION)"
    info "Omarchy base pin: omarchy=$OMARCHY_VERSION"

    # Deterministic chicken-and-egg break (shared with packages.yml x86_64):
    # test/omarchy-keyring-bootstrap.sh fetches the repo db, verifies the
    # omarchy-keyring package against the db's SHA256 entry, extracts the
    # keyrings and populates. Populate BOTH keyrings exactly like the
    # staging key above (host default + the pacstrap GPGDir).
    bash "$REPO_ROOT/test/omarchy-keyring-bootstrap.sh"
    pacman-key --gpgdir "$gpgdir" --populate omarchy >/dev/null 2>&1
    info "omarchy keyring populated (host via shared script + pacstrap keyring)"
fi

pacman_conf="$OUT_DIR/pacman-desktop-install.conf"
if [ "$LEGACY" = yes ]; then
    cat > "$pacman_conf" <<EOF
[options]
Architecture = x86_64
SigLevel = Required DatabaseOptional
NoProgressBar
DisableSandbox
GPGDir = $gpgdir
HoldPkg = pacman glibc

[core]
Include = /etc/pacman.d/mirrorlist

[extra]
Include = /etc/pacman.d/mirrorlist

[archmage-testing]
SigLevel = Required
Server = file://$STAGING
EOF
else
    cat > "$pacman_conf" <<EOF
[options]
Architecture = x86_64
SigLevel = Required DatabaseOptional
NoProgressBar
DisableSandbox
GPGDir = $gpgdir
HoldPkg = pacman glibc

[core]
Include = /etc/pacman.d/mirrorlist

[extra]
Include = /etc/pacman.d/mirrorlist

[omarchy]
Server = https://pkgs.omarchy.org/stable/\$arch

[archmage-testing]
SigLevel = Required
Server = file://$STAGING
EOF
fi

# ---- disk: separate ESP/root sparse files, bare loop mounts, dd assembly.
# Partition-node racing on the shared-host /dev is a live PITFALL (mkrootfs
# x86_64: loopNpN nodes materialize asynchronously and "on some hosts
# never"); bare loop attaches of standalone files sidestep partition scan
# entirely. The final GPT image is assembled by dd at the end.
ESP_IMG="$OUT_DIR/esp.img"
ROOT_IMG="$OUT_DIR/root-btrfs.img"
# Stale images from a failed earlier run carry an old btrfs signature —
# clean them (the final assembled image is cleaned separately).
rm -f "$ESP_IMG" "$ROOT_IMG"
truncate -s $((ESP_MB * 1024 * 1024)) "$ESP_IMG"
truncate -s 7G "$ROOT_IMG"

attach_bare() {  # attach_bare <img> -> prints the bare loop device
    local img="$1" attempt minor node loop
    for attempt in 1 2 3; do
        if loop="$(losetup -f --show "$img" 2>/dev/null)"; then
            printf '%s\n' "$loop"
            return 0
        fi
        # Fallback: instantiate the /dev node for a free index and attach
        # directly (shared-host /dev sometimes never creates the node the
        # loop-control index points at — observed live 03-01).
        [ -e /dev/loop-control ] || mknod /dev/loop-control c 10 237 2>/dev/null || true
        for minor in $(seq 0 127); do
            node="/dev/loop$minor"
            [ -e "$node" ] || mknod "$node" b 7 "$minor" 2>/dev/null || true
            [ -e "$node" ] || continue
            if losetup "$node" "$img" 2>/dev/null; then
                printf '%s\n' "$node"
                return 0
            fi
        done
        sleep 2
    done
    return 1
}

ESP_LOOP="$(attach_bare "$ESP_IMG")" || die "losetup failed for $ESP_IMG"
ROOT_LOOP="$(attach_bare "$ROOT_IMG")" || die "losetup failed for $ROOT_IMG"

mnt="$OUT_DIR/mnt"
mkdir -p "$mnt"
mkfs.vfat -F 32 -n AMDESP "$ESP_LOOP"
mkfs.btrfs -f -L archmage-desktop "$ROOT_LOOP"
mount "$ROOT_LOOP" "$mnt"
btrfs subvolume create "$mnt/@"
btrfs subvolume create "$mnt/@var"
btrfs subvolume create "$mnt/@snapshots"
umount "$mnt"
mount -o compress=zstd:1,subvol=@ "$ROOT_LOOP" "$mnt"
mkdir -p "$mnt/var" "$mnt/.snapshots"
if [ "$LEGACY" = yes ]; then
    mkdir -p "$mnt/esp"
    mount "$ESP_LOOP" "$mnt/esp"
    ESP_MNT="esp"
else
    # limine-entry-tool convention: the ESP IS /boot (omarchy default.conf).
    mkdir -p "$mnt/boot"
    mount "$ESP_LOOP" "$mnt/boot"
    ESP_MNT="boot"
fi
mount -o compress=zstd:1,subvol=@var "$ROOT_LOOP" "$mnt/var"
chattr +C "$mnt/var" 2>/dev/null || true   # NoCOW for DBs (PITFALLS 6)
mount -o compress=zstd:1,subvol=@snapshots "$ROOT_LOOP" "$mnt/.snapshots"

cleanup() {
    umount "$mnt/proc" "$mnt/dev" 2>/dev/null || true
    umount "$mnt/$ESP_MNT" "$mnt/.snapshots" "$mnt/var" "$mnt" 2>/dev/null || true
    losetup -d "$ESP_LOOP" "$ROOT_LOOP" 2>/dev/null || true
}
trap cleanup EXIT INT TERM

# ---- install: desktop stack + archmage overlay from staging (SigLevel
# Required — the 01-02 Required discipline) ----
chroot="$mnt"
# NO manual pseudofs binds here — mkrootfs-x86_64's proven recipe (months of
# green CI) relies on pacstrap mounting the API filesystems itself for the
# transaction and runs the post-pacstrap chroot steps as pure file ops. This
# script originally pre-bound /dev /proc /sys before pacstrap; pacstrap's
# own chroot_setup then stacked fresh proc/sysfs/devtmpfs instances on top
# and the kernel refused the same-superblock restack with EBUSY ("sys
# already mounted or mount point busy" — reproduced on colima/Rosetta, and
# a latent hazard on any runner kernel that enforces it).

if [ "$LEGACY" = yes ]; then
    pacstrap -C "$pacman_conf" -K -G -M -c "$mnt" \
        base linux linux-firmware linux-headers \
        grub efibootmgr os-prober \
        networkmanager ufw \
        pipewire wireplumber pipewire-pulse \
        hyprland uwsm ghostty waybar fuzzel \
        xdg-desktop-portal-hyprland polkit-gnome brightnessctl \
        fcitx5 fcitx5-chinese-addons fcitx5-gtk fcitx5-qt \
        noto-fonts-cjk noto-fonts ttf-jetbrains-mono-nerd \
        gum fzf sudo git \
        snapper snap-pac \
        archmage-desktop
else
    # Omarchy base (D-0.2): the meta package pulls the whole desktop stack
    # (keyring/themes-intros/settings + hyprland quickshell uwsm sddm portals
    # pipewire gum limine* snapper). We add the kernel + firmware, the few
    # ISO-set pieces the meta misses (fastfetch/fzf/brightnessctl/NM/ufw) and
    # our overlay (archmage-desktop pulls archmage-branding).
    pacstrap -C "$pacman_conf" -K -G -M -c "$mnt" \
        base linux-omarchy linux-omarchy-headers linux-firmware \
        "omarchy=$OMARCHY_VERSION" \
        fastfetch fzf brightnessctl \
        networkmanager ufw \
        archmage-desktop
fi

# The chroot config + bootloader phases exec binaries INSIDE the new root.
# Under Rosetta (x86_64-on-ARM local builds via colima) exec needs
# /proc/self/exe, and the build root has no pseudofs of its own (pacstrap
# mounted fresh instances for the transaction and unmounted them). Give the
# build root proc/dev for the chroot phase — safe now that pacstrap is done;
# tolerant so native CI runners are unaffected either way.
mkdir -p "$mnt/proc" "$mnt/dev"
mount --bind /proc "$mnt/proc" 2>/dev/null || \
    info "proc bind unavailable (native runner — not needed)"
mount --bind /dev  "$mnt/dev"  2>/dev/null || true

if [ "$LEGACY" = no ]; then
    # Belt and braces: the 99-archmage-branding hook already ran inside the
    # pacstrap transaction (PostTransaction, after omarchy-settings'
    # .INSTALL re-copied its os-release); re-run once explicitly so the
    # build log shows the applied state and nothing depends on hook
    # ordering inside pacstrap. Idempotent by construction. AFTER the proc
    # bind above: chroot execs need /proc/self/exe under Rosetta.
    chroot "$chroot" /usr/share/archmage/branding/apply-branding.sh
fi

# ---- configuration (chroot) ----
if [ "$LEGACY" = yes ]; then
    LANG=C.UTF-8 chroot "$chroot" /bin/bash -ec '
        set -euo pipefail
        # locale: zh_CN primary with en_US fallback
        printf "en_US.UTF-8 UTF-8\nzh_CN.UTF-8 UTF-8\n" > /etc/locale.gen
        locale-gen
        printf "LANG=zh_CN.UTF-8\n" > /etc/locale.conf
        # timezone + hostname
        ln -sf /usr/share/zoneinfo/Asia/Shanghai /etc/localtime
        printf "archmage-desktop\n" > /etc/hostname
        # fcitx5 wayland IME defaults (environment.d; Omarchy 3.0 --wayland-ime fix)
        mkdir -p /usr/lib/environment.d
        cat > /usr/lib/environment.d/10-archmage-desktop-ime.conf <<ENV
GTK_IM_MODULE=fcitx
QT_IM_MODULE=fcitx
XMODIFIERS=@im=fcitx
INPUT_METHOD=fcitx
ENV
        # user archmage (uid 1000, wheel) — dev-image password convention 1234
        useradd -m -u 1000 -G wheel,video,audio,input archmage
        echo "archmage:1234" | chpasswd
        printf "archmage ALL=(ALL:ALL) ALL\n" > /etc/sudoers.d/archmage
        chmod 440 /etc/sudoers.d/archmage
        # services
        systemctl enable NetworkManager.service
        systemctl enable ufw.service
        systemctl enable fstrim.timer
        # greetd autologin into the Hyprland uwsm session
        pacman -S --noconfirm --needed greetd greetd-tuigreet >/dev/null 2>&1 || true
        mkdir -p /etc/greetd
        cat > /etc/greetd/config.toml <<GREETD
[terminal]
vt = 7

[default_session]
command = "tuigreet --time --remember --cmd uwsm start hyprland.desktop"
user = "archmage"
GREETD
        systemctl enable greetd.service 2>/dev/null || {
            mkdir -p /etc/systemd/system/multi-user.target.wants
            ln -sf /usr/lib/systemd/system/greetd.service \
                /etc/systemd/system/multi-user.target.wants/greetd.service
        }
        # fstab: btrfs subvol mounts by label (ESP mounts are handled by GRUB;
        # no runtime ESP fstab entry needed for the first boot)
        cat > /etc/fstab <<FSTAB
LABEL=archmage-desktop  /           btrfs   rw,compress=zstd:1,subvol=@         0 0
LABEL=archmage-desktop  /var        btrfs   rw,compress=zstd:1,subvol=@var      0 0
LABEL=archmage-desktop  /.snapshots btrfs   rw,compress=zstd:1,subvol=@snapshots 0 0
FSTAB
        # allow NOTHING to silently skip the desktop umbrella
        pacman -Q archmage-desktop >/dev/null
        echo "--- desktop chroot config complete ---"
    '
else
    LANG=C.UTF-8 chroot "$chroot" /bin/bash -ec '
        set -euo pipefail
        # machine-id BEFORE limine enrollment: entries live under
        # $ESP_PATH/$machine_id/<kernel>/ (limine-entry-tool get_machine_id)
        [ -s /etc/machine-id ] || systemd-machine-id-setup
        # locale: zh_CN primary with en_US fallback
        printf "en_US.UTF-8 UTF-8\nzh_CN.UTF-8 UTF-8\n" > /etc/locale.gen
        locale-gen
        printf "LANG=zh_CN.UTF-8\n" > /etc/locale.conf
        # timezone + hostname
        ln -sf /usr/share/zoneinfo/Asia/Shanghai /etc/localtime
        printf "archmage-desktop\n" > /etc/hostname
        # fcitx5 wayland IME defaults (environment.d; Omarchy 3.0 --wayland-ime fix)
        mkdir -p /usr/lib/environment.d
        cat > /usr/lib/environment.d/10-archmage-desktop-ime.conf <<ENV
GTK_IM_MODULE=fcitx
QT_IM_MODULE=fcitx
XMODIFIERS=@im=fcitx
INPUT_METHOD=fcitx
ENV
        # user archmage (uid 1000, wheel) — dev-image password convention 1234
        useradd -m -u 1000 -G wheel,video,audio,input archmage
        echo "archmage:1234" | chpasswd
        printf "archmage ALL=(ALL:ALL) ALL\n" > /etc/sudoers.d/archmage
        chmod 440 /etc/sudoers.d/archmage
        # services: NM + ufw + trim + SDDM (autologin via the conf.d below)
        systemctl enable NetworkManager.service
